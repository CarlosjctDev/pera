import type { AppIconData, AppIconTag, IconName } from '../model/icon.model';

function toIconData(icon: LucideIconData): AppIconData {
  const side = icon.size ?? 24;
  return {
    viewBox: `0 0 ${side} ${side}`,
    nodes: icon.node.map(([tag, attrs]) => ({ tag: tag as AppIconTag, attrs })),
  };
}

function brandIcon(d: string): AppIconData {
  return {
    viewBox: '0 0 24 24',
    nodes: [{ tag: 'path', attrs: { d, fill: 'currentColor' } }],
  };
}

